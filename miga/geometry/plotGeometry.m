function S = plotGeometry(G,nPts,nLines)
%PLOTGEOMETRY Plot a spline geometry and its tensor-product lines.
%
%   S = plotGeometry(G)
%   plots the geometry parametrized by the basis G.
%
%   S = plotGeometry(G,NPTS)
%   specifies the number of evaluation points in each parameter direction.
%   For multidimensional geometries, a scalar NPTS is used in every
%   direction.
%
%   S = plotGeometry(G,NPTS,NLINES)
%   additionally specifies the number of equally spaced tensor-product
%   lines displayed in each parameter direction. By default, five lines
%   are plotted in each direction.
%
%   The function supports parametrizations of curves, surfaces, and
%   volumes. For a parametrization whose range dimension equals the
%   domain dimension, the boundary faces are plotted. For a
%   parametrization with a higher-dimensional range, the interior geometry
%   is plotted together with tensor-product lines.
%
%   Input arguments:
%       G      - Basis representing the spline geometry. G must define a
%                map from an N-dimensional parameter domain to an
%                M-dimensional physical space, with 1 <= N <= 3,
%                1 <= M <= 3, and M >= N.
%
%       NPTS   - Number of evaluation points in each parameter direction.
%                It can be a scalar, in which case the same number is used
%                in every direction, or a vector with one entry per
%                parameter direction. Default: 41.
%
%       NLINES - Number of equally spaced tensor-product lines plotted in
%                each parameter direction. It can be a scalar, in which
%                case the same number is used in every direction, or a
%                vector with one entry per parameter direction.
%                Default: 5.
%
%   Output arguments:
%       S - Handle, or collection of handles, to the graphics objects
%           generated by the plot.
%
%   Notes:
%       If the domain and range have the same dimension, the boundary of
%       the geometry is plotted. In particular, for a surface both boundary
%       curves are displayed, while for a volume the boundary faces are
%       displayed.
%
%       If the range dimension is larger than the domain dimension, the
%       parametrized geometry is plotted directly. Tensor-product lines
%       are added to visualize the parametrization.
%
%       The axes are set to equal scaling. If HOLD is not active before
%       calling the function, its previous state is restored afterwards.
%
%       The function supports the following geometry types:
%
%           parameter domain   physical space   visualization
%           --------------------------------------------------
%           0D                 1D               point
%           1D                 2D               planar curve
%           1D                 3D               space curve
%           2D                 3D               surface



arguments
    G      (1,1) aBasis 
    nPts   (:,1) double {mustBeNonnegative} = 41
    nLines (:,1) double {mustBeNonnegative} = 5
end
domainDim = size(G.domain,1);

if domainDim<1 || domainDim>3 % domainDim
    error('I can only plot lines, surfaces and volumes');
end
if G.rangeSize<1 || G.rangeSize>3
    error('The plot must be 1D, 2D or 3D');
end
if domainDim>G.rangeSize
    error('Geometry should be a map R^n->R^m with m>=n');
end
if isscalar(nPts) && domainDim>1
    nPts=repelem(nPts,domainDim);
end
if isscalar(nLines) && domainDim>1
    nLines=repelem(nLines,domainDim);
end
% plot
tf = ishold;
hold on;
coDim=G.rangeSize-domainDim;
if coDim==0
    S=plotFaces(G,nPts,domainDim);
else
    S=plotBody(G,nPts, domainDim);
end
plotLines(G,nPts,domainDim,nLines);
axis equal
if ~tf; hold 'off'; end
end

function S=plotBody(G,nPts,domainDim)
pts=arrayfun(@(i)linspace(G.domain(i,1),G.domain(i,2),nPts(i)),1:domainDim,'UniformOutput',false);
M=G.evaluate(pts);
M=reshape(M,[G.rangeSize nPts(1)*ones(1,domainDim)]);
S=plotWithDims(M,domainDim,G.rangeSize);
end

function S=plotFaces(G,nPts, domainDim)
pts=arrayfun(@(i)linspace(G.domain(i,1),G.domain(i,2),nPts(i)),1:domainDim,'UniformOutput',false);
for i=1:domainDim
    tmp=pts{i};
    pts{i}=G.domain(i,1);
    M=squeeze(G.evaluate(pts));
    M=reshape(M,[domainDim nPts(1)*ones(1,domainDim-1)]);
    S{2*i-1}=plotWithDims(M,domainDim-1,G.rangeSize);
    pts{i}=G.domain(i,2);
    M=squeeze(G.evaluate(pts));
    M=reshape(M,[domainDim nPts(1)*ones(1,domainDim-1)]);
    S{2*i}=plotWithDims(M,domainDim-1,G.rangeSize);
    pts{i}=tmp;
end
end

function S=plotWithDims(data,domainDim,rangeSize)
if  domainDim==0 && rangeSize==1
    S=plot(data(:),0,'r.','MarkerSize',10);
    ax=gca;
    ax.XAxisLocation = 'origin';
    ax.YColor = 'none';
    ax.Color = 'none';
    ylim([0,eps]);
    xlim('auto');
elseif domainDim==1 && rangeSize==2
    S=plot(data(1,:),data(2,:),'Color','red','LineWidth',1);
    view(2);
elseif domainDim==1 && rangeSize==3
    S=plot3(data(1,:),data(2,:),data(3,:),'Color','black','LineWidth',1);
    view(3);
elseif domainDim==2 && rangeSize==3
    S=surf(squeeze(data(1,:,:)),squeeze(data(2,:,:)),squeeze(data(3,:,:)));
    view(3);
    shading(gca,'interp') 
    colormap([0.3, 0.4, 0.5]); 
    shading interp;
    camlight; 
   % lighting phong;  
else
    error('Can not plot functions of this type');
end
end


function S=plotLines(G,nPts,domainDim,nLines)
domain=G.domain;
lineExtrema=mat2cell(domain,ones(1,domainDim),2);
linePts=arrayfun(@(i)linspace(G.domain(i,1),G.domain(i,2),nPts(i)),1:domainDim,'UniformOutput',false);
linePos=cellfun(@(d,n)linspace(d(1),d(2),n),lineExtrema,num2cell(nLines(:)),"UniformOutput",false);
rangeDim=prod(G.rangeSize);
myNPts=nLines;
for d=1:domainDim
    allPoints=linePos;
    allPoints{d}=linePts{d};
    myNPts(d)=nPts(d);
    v=G.evaluate(allPoints);
    v=v(:,:);
    v=mat2cell(v,ones(1,rangeDim),prod(myNPts)); 
    myWorkToShape=@(w)...
     reshape(...
        permute(...
            reshape(w,myNPts), ...
                [d,1:d-1,d+1:domainDim]), ...
                    [nPts(d),prod(myNPts)/nPts(d)]);
    v=cellfun(myWorkToShape,v,"UniformOutput",false);
    switch(rangeDim)
    case 2
        S=plot(v{:},'Color','red','LineWidth',1);
    case 3
        S=plot3(v{:},'Color','red','LineWidth',1);
    end
    myNPts(d)=nLines(d);
end
end

